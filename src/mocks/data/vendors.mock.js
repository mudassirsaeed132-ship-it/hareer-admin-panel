export function createVendorDetailFromRequest(request) {
  return {
    id: request.id.replace("vendor-request", "vendor"),
    businessName: request.businessName,
    badgeLabel: request.businessName.slice(0, 2).toUpperCase(),
    description:
      "A Brand known for it's luxury perfumes, elegant modest clothing and ...",
    memberSince: "March 2026",
    status: "active",
    owner: {
      name: request.vendorName,
      role: "Store owner",
      avatarLabel: request.vendorName
        .split(" ")
        .map((part) => part[0])
        .join("")
        .slice(0, 2)
        .toUpperCase(),
    },
    metrics: clone(vendorDetailsByIdMock["vendor-001"].metrics),
    orders: clone(vendorDetailsByIdMock["vendor-001"].orders),
    serviceRequests: clone(vendorDetailsByIdMock["vendor-001"].serviceRequests),
    products: clone(vendorDetailsByIdMock["vendor-001"].products),
  };
}